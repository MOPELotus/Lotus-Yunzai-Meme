function normalize(value: string) {
  return value.normalize("NFKC").trim().toLowerCase();
}

export function isExcludedMemeTemplate(key: unknown, tags: readonly unknown[] = []): boolean {
  const id = typeof key === "string" ? normalize(key) : "";
  return excludedKeys.has(id) || tags.some(tag =>
    typeof tag === "string" && originTags.has(normalize(tag).replace(/[\s_:\u00b7・\-]+/gu, "")));
}

export function isRetiredMemeAlias(value: string): boolean {
  return retiredAliases.has(normalize(value));
}
