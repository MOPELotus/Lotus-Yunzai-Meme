interface Point {
  readonly x: number;
  readonly y: number;
}
export interface Pose extends Point {
  readonly image: number;
  readonly width: number;
  readonly height: number;
  readonly angle?: number;
  readonly centered?: true;
}

export interface FixedPoseSpec {
  readonly key: string;
  readonly directory: string;
  readonly inputs: number;
  readonly keywords: readonly string[];
  readonly tags?: readonly string[];
  readonly delayMs: number;
  readonly frames: readonly { readonly source: number; readonly poses: readonly Pose[] }[];
  readonly layer: "above" | "under" | "under-mask" | "paper" | "masked-top";
  readonly prepare?: "square" | "circle" | "book" | "basketball";
  readonly cover?: true;
  readonly streamPaletteLimits?: readonly [number, ...number[]];
}

function pose(image: number, x: number, y: number, width: number, height: number, angle?: number, centered?: true): Pose {
  return { image, x, y, width, height, angle, centered };
}

